import React, { useState } from "react";
import { useNavigate } from "react-router-dom";
import axios from "axios";
import { Link } from "react-router-dom";
import ForgotPassword from "./ForgotPassword";

function LoginPopup({ isOpen, onClose, redirectTo }) {
    const [email, setEmail] = useState("");
    const [password, setPassword] = useState("");
    const [showPassword, setShowPassword] = useState(false);
    const [loading, setLoading] = useState(false);
    const [error, setError] = useState("");
    const navigate = useNavigate();

    const handleLogin = async (e) => {
        e.preventDefault();
        setLoading(true);
        setError("");

        try {
            const response = await axios.post(`${process.env.REACT_APP_API_URL || 'http://127.0.0.1:8000'}/auth/login`, {
                email: email,
                password: password
            });

            // Save JWT token to localStorage
            localStorage.setItem("token", response.data.token);

            // Close popup
            onClose();

            // Redirect to homepage (maintenance screen will show if maintenance mode is enabled)
            navigate("/homepage");
        } catch (err) {
            const errorMessage = err.response?.data?.detail || err.message;

            // Check if it's a maintenance mode error
            if (err.response?.status === 503) {
                setError("Site is currently under maintenance. Please try again later.");
            }
            // Check if it's an email verification error
            else if (err.response?.status === 403 && errorMessage.includes("Email not verified")) {
                setError("Please verify your email before logging in. Check your email for verification code.");
            }
            // Check if it's a network error
            else if (err.code === 'ERR_NETWORK' || err.message.includes('Network Error')) {
                setError("Unable to connect to the server. Please check your internet connection and try again.");
            }
            else {
                setError(errorMessage);
            }
        } finally {
            setLoading(false);
        }
    };

    const handleSignupClick = () => {
        localStorage.removeItem("token"); // clear any old invalid token
        navigate("/signup", { replace: true });
    };


    if (!isOpen) return null;

    return (
        <div style={{
            position: "fixed",
            top: 0,
            left: 0,
            right: 0,
            bottom: 0,
            backgroundColor: "rgba(0, 0, 0, 0.5)",
            display: "flex",
            alignItems: "center",
            justifyContent: "center",
            zIndex: 10000
        }}>
            <div style={{
                backgroundColor: "white",
                borderRadius: "12px",
                padding: "2rem",
                width: "400px",
                maxWidth: "90vw",
                boxShadow: "0 10px 30px rgba(0,0,0,0.3)",
                position: "relative"
            }}>
                {/* Header */}
                <div style={{
                    textAlign: "center",
                    marginBottom: "1.5rem"
                }}>
                    <h2 style={{
                        margin: "0 0 0.5rem 0",
                        color: "#1a4d3a",
                        fontSize: "1.5rem",
                        fontWeight: "600"
                    }}>
                        Welcome Back
                    </h2>
                    <p style={{
                        margin: 0,
                        color: "#666",
                        fontSize: "0.9rem"
                    }}>
                        Sign in to access all features
                    </p>
                </div>

                {/* Login Form */}
                <form onSubmit={handleLogin}>
                    <div style={{ marginBottom: "1rem" }}>
                        <label style={{
                            display: "block",
                            marginBottom: "0.5rem",
                            fontWeight: "500",
                            color: "#333"
                        }}>
                            Email
                        </label>
                        <input
                            type="email"
                            value={email}
                            onChange={(e) => setEmail(e.target.value)}
                            required
                            style={{
                                width: "100%",
                                padding: "0.75rem",
                                border: "1px solid #ddd",
                                borderRadius: "6px",
                                fontSize: "1rem",
                                boxSizing: "border-box"
                            }}
                            placeholder="Enter your email"
                        />
                    </div>

                    <div style={{ marginBottom: "1.5rem" }}>
                        <label style={{
                            display: "block",
                            marginBottom: "0.5rem",
                            fontWeight: "500",
                            color: "#333"
                        }}>
                            Password
                        </label>
                        {/* Add wrapper div for password field */}
                        <div style={{ position: 'relative' }}>
                            <input
                                type={showPassword ? "text" : "password"}
                                value={password}
                                onChange={(e) => setPassword(e.target.value)}
                                required
                                style={{
                                    width: "100%",
                                    padding: "0.75rem",
                                    paddingRight: '45px',
                                    border: "1px solid #ddd",
                                    borderRadius: "6px",
                                    fontSize: "1rem",
                                    boxSizing: "border-box"
                                }}
                                placeholder="Enter your password"
                            />
                            {/* Add custom eye icon */}
                            <span
                                onClick={() => setShowPassword(!showPassword)}
                                style={{
                                    cursor: 'pointer',
                                    position: 'absolute',
                                    right: '12px',
                                    top: '50%',
                                    transform: 'translateY(-50%)',
                                    color: '#666',
                                    padding: '8px',
                                    userSelect: 'none',
                                    zIndex: 10
                                }}
                            >
                                <img
                                    src={showPassword ?
                                        "https://res.cloudinary.com/dqmmgk88b/image/upload/v1762348022/SY_MBYLL_cioicv.svg" :
                                        "https://res.cloudinary.com/dqmmgk88b/image/upload/v1762348022/SY_HAP_yencim.svg"}
                                    alt={showPassword ? "Hide password" : "Show password"}
                                    style={{
                                        width: '18px',
                                        height: '18px',
                                        objectFit: 'contain'
                                    }}
                                />
                            </span>
                        </div>
                    </div>

                    {error && (
                        <div style={{
                            backgroundColor: "#f8d7da",
                            color: "#721c24",
                            padding: "0.75rem",
                            borderRadius: "6px",
                            marginBottom: "1rem",
                            fontSize: "0.9rem"
                        }}>
                            {error}
                        </div>
                    )}

                    <button
                        type="submit"
                        disabled={loading}
                        style={{
                            width: "100%",
                            backgroundColor: loading ? "#ccc" : "#1a4d3a",
                            color: "white",
                            border: "none",
                            padding: "0.75rem",
                            borderRadius: "6px",
                            fontSize: "1rem",
                            fontWeight: "500",
                            cursor: loading ? "not-allowed" : "pointer",
                            marginBottom: "1rem",
                            transition: "background-color 0.2s"
                        }}
                    >
                        {loading ? "Signing In..." : "Sign In"}
                    </button>
                </form>
                <button
                    onClick={() => {
                        console.log("Closing modal and redirecting...");
                        onClose();
                        // Force navigation after a tiny delay to ensure modal is closed
                        setTimeout(() => {
                            window.location.href = "/forgot-password";
                        }, 10);
                    }}
                    style={{
                        backgroundColor: "transparent",
                        border: "none",
                        color: "#1a4d3a",
                        textDecoration: "underline",
                        cursor: "pointer",
                        fontSize: "inherit",
                        padding: 0
                    }}
                >
                    Forgot Password?
                </button>

                {/* Signup Link */}
                <div style={{
                    textAlign: "center",
                    paddingTop: "1rem",
                    borderTop: "1px solid #eee"
                }}>
                    <p style={{
                        margin: "0 0 0.5rem 0",
                        color: "#666",
                        fontSize: "0.9rem"
                    }}>
                        Don't have an account?
                    </p>
                    <button
                        onClick={handleSignupClick}
                        style={{
                            backgroundColor: "transparent",
                            color: "#1a4d3a",
                            border: "none",
                            fontSize: "0.9rem",
                            fontWeight: "500",
                            cursor: "pointer",
                            textDecoration: "underline"
                        }}
                    >
                        Sign up here
                    </button>
                </div>

                {/* Close Button */}
                <button
                    onClick={onClose}
                    style={{
                        position: "absolute",
                        top: "1rem",
                        right: "1rem",
                        backgroundColor: "transparent",
                        border: "none",
                        fontSize: "1.5rem",
                        cursor: "pointer",
                        color: "#666"
                    }}
                >
                    ×
                </button>
            </div>
        </div>
    );
}

export default LoginPopup;